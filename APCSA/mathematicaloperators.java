package APCSA;
public class mathematicaloperators {
public static void main(String[] args) {
    int x = 5;
int y = 10;
System.out.println("x: " + x + ", y: " + y);

x = y;
System.out.println("x: " + x + ", y: " + y);

y = 20;
System.out.println("x: " + x + ", y: " + y);

int z = x + y;
System.out.println("x: " + x + ", y: " + y);
System.out.println("z: " + z);

x = 7;
System.out.println("x: " + x + ", y: " + y);
System.out.println("z: " + z);
}
}

